// Generates a film's index.html from its scenes.json and the song. Run it inside the film's folder: node ../shared/build.mjs
// shared/lyrics.json owns the words and when they are sung, scenes.json owns the cuts, compositions/<id>.html owns the pictures.
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";

const shared = new URL(".", import.meta.url);
const song = JSON.parse(readFileSync(new URL("lyrics.json", shared), "utf8"));
const { scenes, scripts = [], styles = ["assets/style.css"] } = JSON.parse(readFileSync("scenes.json", "utf8"));

const beat = (n) => song.firstBeat + (n * 60) / song.bpm;
// A scene starts at a bar or beat of the song, at a film second, or just before a lyric line.
function startOf(s, i) {
  if (i === 0) return 0;
  if (s.at != null) return s.at;
  if (s.bar != null) return beat(s.bar * song.beatsPerBar + (s.beat ?? 0));
  if (s.beat != null) return beat(s.beat);
  const line = song.lines.find((l) => l.id === s.line);
  if (!line) throw new Error(`Scene "${s.id}" needs "bar", "beat", "at" or a "line" that exists`);
  return line.start - (s.lead ?? 0.08);
}
const starts = scenes.map(startOf);
const timed = scenes.map((s, i) => {
  const end = starts[i + 1] ?? song.duration;
  if (end <= starts[i]) throw new Error(`Scene "${s.id}" starts at ${starts[i]}, after the next scene starts`);
  if (!existsSync(`compositions/${s.id}.html`)) throw new Error(`compositions/${s.id}.html is missing`);
  return { id: s.id, start: +starts[i].toFixed(3), dur: +(end - starts[i]).toFixed(3) };
});

mkdirSync("assets", { recursive: true });
copyFileSync(new URL("kit.js", shared), "assets/kit.js");
copyFileSync(new URL("song.m4a", shared), "assets/song.m4a");

const hosts = timed
  .map((s) => `      <div id="${s.id}" data-composition-id="${s.id}" data-composition-src="compositions/${s.id}.html" data-start="${s.start}" data-duration="${s.dur}" data-track-index="1" data-track-kind="graphics" data-width="1920" data-height="1080"></div>`)
  .join("\n");
const sceneTimes = Object.fromEntries(timed.map((s) => [s.id, { start: s.start, dur: s.dur }]));

writeFileSync(
  "index.html",
  `<!doctype html>
<!-- Generated by ../shared/build.mjs. Edit scenes.json or compositions/, then run: node ../shared/build.mjs -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1920, height=1080" />
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.15.0/dist/gsap.min.js"></script>
${styles.map((href) => `    <link rel="stylesheet" href="${href}" />`).join("\n")}
    <script>window.SONG = ${JSON.stringify(song)}; window.SCENES = ${JSON.stringify(sceneTimes)};</script>
    <script src="assets/kit.js"></script>
${["assets/lib.js", ...scripts].filter((src) => existsSync(src)).map((src) => `    <script src="${src}"></script>`).join("\n")}
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="${song.duration}" data-width="1920" data-height="1080">
${hosts}
      <audio id="song" src="assets/song.m4a" data-start="0" data-track-index="3" data-volume="1"></audio>
    </div>
    <script>
      window.__timelines["main"] = gsap.timeline({ paused: true });
    </script>
  </body>
</html>
`,
);

for (const s of timed) {
  const sung = song.lines.filter((l) => l.start < s.start + s.dur && l.end > s.start).map((l) => l.id);
  console.log(`${s.id.padEnd(12)} ${s.start.toFixed(2).padStart(6)}  ${s.dur.toFixed(2).padStart(6)} s  ${sung.join(" ")}`);
}
console.log(`${scenes.length} scenes, ${song.duration} s`);
