import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import { readFile, writeFile } from 'node:fs/promises';
import { realpathSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

// The folder viewer's page is one string with inline script and style only
// (its CSP has no 'self'), so it carries the other pages' tooltip
// (viewer/tooltip.ts) as `src/tooltip-script.ts`. That module is committed:
// the website and lib compile this package's `src` directly (Vite, Vitest, and
// tsc path aliases), from checkouts where nothing has run this script. Its
// header records a hash of the sources it was built from, and
// test/tooltip.test.mjs compares only that, so an esbuild release that
// minifies differently never fails a test.
const absWorkingDir = fileURLToPath(new URL('../', import.meta.url));
export const OUT = fileURLToPath(new URL('../src/tooltip-script.ts', import.meta.url));
const HASH = /^\/\/ Sources: ([0-9a-f]+)$/m;

/** The hash `module` (a generated `src/tooltip-script.ts`) records. */
export const recordedHash = module => HASH.exec(module)?.[1] ?? null;

/** What `src/tooltip-script.ts` holds for the current `viewer/tooltip.ts`. */
export async function tooltipScriptModule() {
  const [script, style] = await Promise.all([
    build({
      absWorkingDir, write: false, bundle: true, minify: true, format: 'iife', platform: 'browser', target: 'es2022', logLevel: 'silent', metafile: true,
      stdin: { contents: "import { installTooltips } from './tooltip'; installTooltips();", resolveDir: 'viewer', loader: 'ts' },
      loader: { '.css': 'empty' },
    }),
    build({ absWorkingDir, write: false, bundle: true, minify: true, logLevel: 'silent', metafile: true, entryPoints: ['viewer/tooltip.css'] }),
  ]);
  const js = script.outputFiles[0].text.trim(), css = style.outputFiles[0].text.trim();
  if (/<\/script/i.test(js) || /<\/style/i.test(css)) throw new Error('the tooltip cannot be inlined');
  return '// Generated by scripts/build-tooltip-script.mjs from viewer/tooltip.ts. Do not edit.\n'
    + `// Sources: ${await sourceHash([script.metafile, style.metafile])}\n`
    + '/** The built-in pages\' tooltip for a page that inlines its script and style. */\n'
    + `export const TOOLTIP_STYLE = ${JSON.stringify(css)};\n`
    + `export const TOOLTIP_SCRIPT = ${JSON.stringify(js)};\n`;
}

/** A hash of every file the builds behind `metafiles` read, by path and
 * content, line endings aside. */
async function sourceHash(metafiles) {
  const paths = [...new Set(metafiles.flatMap(m => Object.keys(m.inputs)))].filter(p => !p.startsWith('<')).sort();
  const hash = createHash('sha256');
  for (const path of paths) hash.update(`${path}\0${(await readFile(new URL(`../${path}`, import.meta.url), 'utf8')).replace(/\r\n/g, '\n')}\0`);
  return hash.digest('hex').slice(0, 16);
}

// `node scripts/build-tooltip-script.mjs` rewrites it; test/tooltip.test.mjs fails while its sources have changed since.
if (process.argv[1] && realpathSync(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = await tooltipScriptModule();
  if (await readFile(OUT, 'utf8').catch(() => '') !== next) await writeFile(OUT, next);
}
